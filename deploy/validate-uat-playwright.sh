#!/usr/bin/env bash
# Repo-side contract for the UAT Playwright harness. Does not hit live UAT.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CFG="$ROOT_DIR/web/playwright.uat.config.ts"
ANON="$ROOT_DIR/web/e2e-uat/anonymous.spec.ts"
AUTH="$ROOT_DIR/web/e2e-uat/authenticated.spec.ts"

pass() { echo "PASS: $1"; }
fail() { echo "FAIL: $1"; exit 1; }

[[ -f "$CFG" ]] || fail "missing web/playwright.uat.config.ts"
[[ -f "$ANON" ]] || fail "missing anonymous UAT spec"
[[ -f "$AUTH" ]] || fail "missing authenticated UAT spec"

grep -q 'UAT_PUBLIC_BASE_URL' "$CFG" || fail "config must read UAT_PUBLIC_BASE_URL"
grep -q '1440' "$CFG" && grep -q '900' "$CFG" || fail "desktop viewport 1440x900 required"
grep -q '390' "$CFG" && grep -q '844' "$CFG" || fail "mobile viewport 390x844 required"
grep -q 'thesocialcollectivesg.com' "$CFG" || fail "config must refuse the shared CRM host"
grep -q 'retain-on-failure' "$CFG" || fail "failure artifacts (trace/screenshot) required"
grep -q 'https://uat.cohestra.app' "$CFG" && fail "do not hardcode the UAT host in the Playwright config"
grep -q 'test.skip' "$AUTH" || fail "authenticated flow must skip without dedicated secrets"
grep -q 'UAT_AUTO_BASIC_EMAIL' "$AUTH" || fail "authenticated flow must use dedicated automation env names"
LAYER_A="$ROOT_DIR/web/e2e-uat/recaptcha-layer-a.spec.ts"
[[ -f "$LAYER_A" ]] || fail "missing Layer A recaptcha spec"
grep -q 'does not solve a live Google challenge' "$LAYER_A" || fail "Layer A must not solve the live challenge"
grep -q 'empty CAPTCHA token is rejected' "$LAYER_A" || fail "Layer A must reject empty CAPTCHA"
grep -q 'invalid CAPTCHA token is rejected' "$LAYER_A" || fail "Layer A must reject invalid CAPTCHA"
grep -q 'waits for real UAT recaptcha keys' "$LAYER_A" && fail "Layer A must not skip after the real UAT recaptcha gate"
HELPER="$ROOT_DIR/web/e2e-uat/otp-mailbox.ts"
[[ -f "$HELPER" ]] || fail "missing web/e2e-uat/otp-mailbox.ts"
grep -q 'UAT_OTP_MAILBOX_HOST' "$HELPER" || fail "mailbox helper must read Environment uat names"
grep -q 'personal mailbox credentials are forbidden' "$HELPER" || fail "mailbox helper must refuse personal inboxes"
grep -q 'readSignupOtp' "$AUTH" || fail "authenticated UAT must use the dedicated OTP mailbox helper"
CORE="$ROOT_DIR/web/e2e-uat/operator-core-flows.spec.ts"
[[ -f "$CORE" ]] || fail "missing 19.5 operator core-flow spec"
grep -q 'UAT_AUTO_BASIC_EMAIL' "$CORE" || fail "19.5 must use Basic automation env names"
grep -q 'UAT_AUTO_PRO_EMAIL' "$CORE" || fail "19.5 must use Pro automation env names"
grep -q 'UAT_AUTO_BASIC_EMAIL/PASSWORD are not mapped' "$CORE" || fail "19.5 must skip until Basic aliases are mapped"
grep -q 'UAT_AUTO_PRO_EMAIL/PASSWORD are not mapped' "$CORE" || fail "19.5 must skip until Pro aliases are mapped"
grep -q 'otp-mailbox' "$CORE" && fail "19.5 must not import the OTP mailbox helper"
grep -q 'UAT_OTP_MAILBOX' "$CORE" && fail "19.5 must not require OTP mailbox secrets"
grep -q 'workspaceOrigin' "$CORE" || fail "19.5 must log in on the tenant host, not marketing apex"
grep -q '/dashboard' "$CORE" || fail "19.5 dashboard must open /dashboard, not public home"
grep -q 'networkidle' "$CORE" || fail "19.5 login must wait for hydration before submit"
grep -q 'method="post"' "$ROOT_DIR/web/components/auth/login-form.tsx" || fail "login form must POST so a pre-hydration submit cannot put credentials in the query string"
grep -q 'Basic website is Core-locked' "$CORE" || fail "19.5 must cover Basic website/stub lock"
grep -q 'Pro website studio and public branding' "$CORE" || fail "19.5 must cover Pro website branding"
grep -q 'Pro create, publish, share, register, dedup, CSV, and campaign test-send' "$CORE" || fail "19.5 must cover the canonical Pro mutating walk"
grep -q '19.5 Harness' "$CORE" || fail "19.5 mutating walk must use a dedicated harness community"
grep -Fq 'items?.[0]' "$CORE" && fail "19.5 must not reuse the first catalog community (default template clone 500)"
grep -q 'campaigns/send-test' "$CORE" || fail "19.5 campaign proof must use send-test"
grep -q 'admin/campaigns/send"' "$CORE" && fail "19.5 must not POST a campaign list blast"
grep -q '/unpublish' "$CORE" || fail "19.5 must unpublish harness activities, not archive the tenant"
grep -q 'Public registration URL' "$CORE" || fail "19.5 Share kit proof must use the labeled registration URL input"
grep -q 'tab=share' "$CORE" || fail "19.5 Share kit proof must open the share tab so the URL input is visible"
DEPLOY="$ROOT_DIR/.github/workflows/deploy.yml"
grep -q 'UAT_AUTO_PRO_EMAIL' "$DEPLOY" || fail "Deploy UAT browser job must pass UAT_AUTO_PRO_EMAIL"
grep -q 'UAT_AUTO_PRO_PASSWORD' "$DEPLOY" || fail "Deploy UAT browser job must pass UAT_AUTO_PRO_PASSWORD"
grep -q 'UAT_AUTO_BASIC_SLUG' "$DEPLOY" || fail "Deploy UAT browser job must pass UAT_AUTO_BASIC_SLUG"
grep -q 'UAT_AUTO_PRO_SLUG' "$DEPLOY" || fail "Deploy UAT browser job must pass UAT_AUTO_PRO_SLUG"
grep -q 'vars.UAT_AUTO_BASIC_SLUG || secrets.UAT_AUTO_BASIC_SLUG' "$DEPLOY" || fail "Basic slug must come from Environment vars with secret fallback, not a hardcoded tenant"
grep -Fq 'picklemania' "$CORE" && fail "19.5 must not hardcode the Basic tenant slug"
grep -q 'getByLabel(/password/i)' "$AUTH" && fail "authenticated UAT must not use a loose password label (Show-password collision)"
grep -q 'locator("#password")' "$AUTH" || fail "authenticated UAT must fill the password input by id"
grep -q 'sign in to workspace' "$AUTH" || fail "authenticated UAT must submit Sign in to workspace, not a broad continue match"
grep -q 'networkidle' "$AUTH" || fail "authenticated UAT login must wait for hydration before submit"
pass "UAT Playwright contract"

echo "uat-playwright contract OK"
